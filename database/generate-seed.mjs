// Generates database/seed.sql from the frontend mock catalogue so both stay in sync.
//   node database/generate-seed.mjs > database/seed.sql
import { authors } from '../frontend/src/data/authors.ts';
import { books } from '../frontend/src/data/books.ts';
import { categories } from '../frontend/src/data/categories.ts';

const q = (v) => `'${String(v).replaceAll("'", "''")}'`;
const out = [];
const emit = (s = '') => out.push(s);

const publishers = [...new Set(books.map((b) => b.publisher))];

emit('-- GENERATED by database/generate-seed.mjs — do not edit by hand.');
emit('BEGIN;');
emit();

emit('INSERT INTO categories (id, label, sort_order) VALUES');
emit(
  categories
    .filter((c) => c.id !== 'all')
    .map((c, i) => `  (${q(c.id)}, ${q(c.label)}, ${i + 1})`)
    .join(',\n') + ';',
);
emit();

emit('INSERT INTO authors (id, name, bio) VALUES');
emit(authors.map((a) => `  (${q(a.id)}, ${q(a.name)}, ${q(a.bio)})`).join(',\n') + ';');
emit();

emit('INSERT INTO publishers (name) VALUES');
emit(publishers.map((p) => `  (${q(p)})`).join(',\n') + ';');
emit();

emit('INSERT INTO books (id, title, subtitle, author_id, publisher_id, category_id, tags, format, price, language, isbn, published_at, stock, rating, rating_count, copies_sold) VALUES');
emit(
  books
    .map((b) => {
      const tags = `ARRAY[${b.tags.map(q).join(', ')}]::text[]`;
      const stock = b.format === 'eBook' ? 'NULL' : '100';
      return `  (${q(b.id)}, ${q(b.title)}, ${q(b.subtitle)}, ${q(b.authorId)}, (SELECT id FROM publishers WHERE name = ${q(b.publisher)}), ${q(b.categoryId)}, ${tags}, ${q(b.format)}, ${b.price}, ${q(b.language)}, ${q(b.isbn)}, ${q(b.publishedAt)}, ${stock}, ${b.rating}, ${Math.round(b.sells * 0.3)}, ${b.sells})`;
    })
    .join(',\n') + ';',
);
emit();

emit('INSERT INTO coupons (code, kind, value, max_discount, min_subtotal, description) VALUES');
emit("  ('BOOKWORM20', 'flat', 20, NULL, 80, '20 RON off orders above 80 RON'),");
emit("  ('READ10', 'percent', 10, 30, 0, '10% off, up to 30 RON');");
emit();
emit('COMMIT;');

process.stdout.write(out.join('\n') + '\n');
